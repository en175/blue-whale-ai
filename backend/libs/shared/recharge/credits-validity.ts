/* ============================================
 * 到账积分的有效期口径（PRD §9.5）：**自订单支付成功时间起算**，按配置的月数加。
 *
 * ── 为什么起算点是「支付成功时刻」而不是「下单时刻」 ──────────────────────────
 *
 * 两件事差得很远：用户下单后隔 25 分钟才付款是常事，网关订单有效期 2 小时。
 * 按**下单**时刻算，等于把用户实际能用到的那段时间白白扣掉一截 —— 运营配「6 个月」，
 * 用户看到的是「6 个月减掉他犹豫的那半小时」，而且扣多少取决于他犹豫了多久。
 * PRD §9.5 写得很明确：「自订单支付成功时刻起算」。
 *
 * ── 为什么快照存的是**月数**而不是算好的时刻 ──────────────────────────────────
 *
 * 下单那一刻**根本还不知道**支付成功时刻（订单可能几十分钟后才被付掉），
 * 所以「下单时算好一个时刻存进订单」这条路的产物必然与真实发放的有效期差一截
 * ——那是两个口径在漂移，而订单快照（`recharge_orders`）存在的全部意义恰恰是
 * 「用户当时看到的是什么」。存**月数**（`credits_valid_months`）则只有一处算：
 * 发放那一刻用 `paid_pending_at + 月数` 折出真正的到期时刻，并把同一个值同时交给
 * billing（显式 `expiresAt`）与订单快照（`credits_expire_at`）。
 *
 * ── 落地范围 ──────────────────────────────────────────────────────────────────
 *
 * 「到期批次一次性过期并写过期流水」（§9.5）由 billing 的过期核销任务负责，不在本仓。
 * 这里只负责**把承诺的那一列变成真实的那一列**，且保证「发给 billing 的到期时刻」
 * 与「订单快照记的到期时刻」是同一个值。
 * ============================================ */

/**
 * 支付成功时刻 + N 个月 = 这批积分真正的到期时刻。
 *
 * <p>按**月**加：`Date.setMonth` 在 8/31 + 6 个月时会溢出到 3/3，
 * 那是 `new Date` 的既有语义，这里不做「钳到月末」的特殊处理 ——
 * 有效期是一个承诺的量级（2 年），不是精确到日的对账口径。
 *
 * <p>不修改传入的 Date：调用方那份（`paid_pending_at`）还要接着用。
 */
export function creditsExpireAt(paidAt: Date, creditsValidMonths: number): Date {
  const expire = new Date(paidAt.getTime());
  expire.setMonth(expire.getMonth() + creditsValidMonths);
  return expire;
}
