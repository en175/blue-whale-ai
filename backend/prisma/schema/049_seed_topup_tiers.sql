-- 换个说法：它是**种子**，不是**单例**。运营删掉某一档、改名、改价，都不会被本文件「纠正」回来
-- （迁移只跑一次，也不重放）。
--
-- ── 三个价格的填法：PRD 只给了一个价，所以**不编造划线价** ────────────────────────
-- PRD §6.1 每个档位只有一个价（¥499 等）。它没有给划线价，所以我们**不发明一个**：
--   `original_price = price = PRD 给的那个价`、`discount = 1.0000`（无折扣）。
-- 于是用户侧卡片上不出现划线价 —— 这是诚实的：没有原价就别画一道划掉的价。
-- 将来运营要做活动，在后台把原价调高、折扣调低即可（`price = 原价 × 折扣` 仍由 repo 派生）。
--
-- ⚠️ **积分与这两个价没有任何换算关系**（见迁移 048 的列注释）：
--   ¥499 → 7,500 积分（不是 499×15=7,485）、¥5,999 → 90,000 积分（不是 5999 的倍数）。
--   看到「对不上」不要去改任何一个数，那两列本来就不参与积分计算。
--
-- ── `amount`（遗留 quota 列）照 `base_credits` 填，同值 ───────────────────────────
-- `amount` 是 new-api 记账时代写进去的 quota（原价 × 500_000 那种量级），**读路径已不再信它**
