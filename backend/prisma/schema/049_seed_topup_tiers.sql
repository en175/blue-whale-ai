-- ⚠️ **「首购」这件事产品还没定形**（每档独立算一次？还是每账号只一次？），
--    本列**不回答**那个问题 —— 它只回答「这一档**参不参与**首购活动」。
--    PRD §6.1 给 6 档**每一档**都配了首购标签（「首购加赠 50%」/「首购超级翻倍」），
--    所以 6 行都填 1；发放与否的判定属模块 C（#40，停放中），届时再定。
--    填 1 是**方向保守的那一边**：档位参与活动 = 展示与赠送口径一致，
