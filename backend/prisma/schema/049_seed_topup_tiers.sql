-- ── 「初始化」≠「写死」（PRD §6.1 与本次初始化的张力，先解释清楚）─────────────────
-- PRD §6.1 要求「价格、基础积分、赠送积分、标签、排序**均应由后台配置，不在代码中写死**」。
-- 本迁移写进库的是一份**初始值**：跑完之后运营在「充值档位」页照常改，改的是什么就是什么。
