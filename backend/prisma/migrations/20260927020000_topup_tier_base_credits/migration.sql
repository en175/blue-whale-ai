-- 通用积分卡：基础积分（base_credits）改为**配置值**，不再是派生值。
--
-- ── 本迁移推翻迁移 047 「支付价格与基础积分仍是派生量」里关于积分的那一半 ──────────
-- 047 的口径是 `amount = 原价 × 换算率`。产品 2026-09-27 明确：**不是**。
--
--   充值侧的「元 → 积分」与消费锚点「1 元 = 15 积分」不是一回事 —— **充值常有折扣**。
--   PRD §6.1 的轻量尝鲜是 ¥499 → **7,500** 积分，而 499 × 15 = **7,485**，对不上；
--   且 7,500 明显是「取整齐过的数」（499×15 向上凑到 7,500），不是算出来的。
--
-- 所以基础积分从「派生」变成「配置」：**运营在后台填什么，用户下单就给什么**。
--
-- ── ⚠️ 原价 + 折扣保留，但只为展示划线价，与积分**再无数学关系** ──────────────────
-- 这是本迁移要钉死的第一件事，写给下一个人：
--   · `price = original_price × discount` 仍成立（实付 = 原价 × 折扣）；
--   · **积分不再是 `original_price × 任何东西`**。¥499 的档可以给 7,500 积分，
--     ¥5,999 的档可以给 90,000 —— 都不是原价的整数倍，**这不是 bug，不要拿积分
--     去除原价、也不要为了「凑成倍数」去改其中任何一个数**。
--   · 换算法（1 元 = 多少积分）只用于「自定义充值」的反算（模块 B，未做），
--     档位积分与它无关。
--
-- ── 存量行落在 0，本迁移**不回填** ──────────────────────────────────────────────
-- 19 行存量档位的「此刻展示积分」是读路径现算出来的（原价 × 当时的换算率），
-- 而换算率住在 billing 的定价目录里（**运行时配置**，SQL 读不到）。
-- 硬写一个 15 之类的常数去回填，等于把一条运行时口径冻进版本化迁移 —— 那正是本迁移
-- 要废掉的那条公式，赌错了还会静默改掉所有存量档位的积分。
-- 所以：存量行落 0（= 还没配过），**方向是保守的** —— 下单路径拒绝 0 积分档位
-- （见 `RechargeService.createOrder`：宁可下不了单，也不发 0 积分），
-- 管理端列表里「积分数 0」也一眼能看见。运营补配即可。
--
-- ── 前置校验（执行前人工确认，须有输出）──────────────────────────────────────
--   SELECT id, name, original_price, status, amount FROM topup_tiers WHERE is_delete = 0;
-- 存量行执行后会全部变成 base_credits = 0（上一条已说明理由）：
-- 上架中的行需要运营在「充值档位」页逐个补配基础积分，否则用户侧下单会被拒。
SET NAMES utf8mb4;

ALTER TABLE topup_tiers
  ADD COLUMN base_credits BIGINT NOT NULL DEFAULT 0
    COMMENT '基础积分（整数积分）：**配置值，不是派生值**。用户下单到账的就是这个数（写进 recharge_orders.credits 的那一个来源）。原价 × 折扣只为展示划线价，与积分**再无数学关系**——充值常有折扣，¥499 可以给 7,500 积分（499×15=7,485 是巧合不是公式），看到「不是原价的整数倍」不要去修它。0 = 还没配过基础积分：下单会被拒（宁可下不了单，也不发 0 积分）';
