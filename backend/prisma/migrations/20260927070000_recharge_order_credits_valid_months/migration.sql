-- 通用积分卡：订单快照记**有效期月数**（运营在档位 / 自定义充值上配的那个数）。
--
-- 依据 PRD §10.2「积分有效期」（必填）与 §9.5「自订单支付成功时间起算」。
--
-- ── 为什么快照存月数，而不是算好的到期时刻 ────────────────────────────────────
-- PRD §9.5 的起算点是「**支付成功**时刻」，而下单那一刻根本还没有它：网关订单有效期 2 小时，
-- 用户下单后隔 25 分钟才付款是常事。于是「下单时按当前时间算一个到期时刻存进去」这条路
-- 必然与真实发放的有效期差一截 —— 差多少取决于用户犹豫了多久。那是两个口径在漂移。
--
-- 存**月数**则只有一处算：发放那一刻（`RechargeService.fulfill`）用
-- `paid_pending_at + credits_valid_months` 折出到期时刻，同一个值既作为显式 `expiresAt`
-- 交给 billing（否则运营配 6 个月会被 billing 的来源策略按 2 年发）、又写回
-- `credits_expire_at`（订单快照记的必须是**真实发出去那批**的到期时刻）。
--
-- ── 与 `credits_expire_at` 的分工（本列不改那一列的定义）──────────────────────
--   · `credits_valid_months`：下单时冻结的**承诺**（配置快照），本列上线起新单都有值；
--   · `credits_expire_at`    ：发放后落地的**事实**（真实发给 billing 的那个时刻），
--     下单时先写 NULL（那一刻还算不出来），由 `markPaid` 写上。
-- 此前 `credits_expire_at` 只有自定义充值那条在**下单**时写过（按当时的时间算），
-- 档位那条恒为 NULL —— 两者都不对：一个算错了起算点，一个干脆没写。
--
-- 可空：本列上线前的订单没有它。那种单发放时不传 `expiresAt`，由 billing 按来源策略
-- （`purchased` = 2 年）决定 —— 与它们当初下的单口径一致。**不给默认值**：
-- 默认值会让存量行凭空多出一个「24 个月」的承诺，而那些单从来没有过这个快照。
SET NAMES utf8mb4;

ALTER TABLE `recharge_orders`
  ADD COLUMN `credits_valid_months` INT NULL
    COMMENT '到账积分有效期快照（月，来自档位/自定义充值配置）。到期时刻发放时按 paid_pending_at + 它算；NULL = 本列上线前的存量单';
