-- 通用积分卡：软删 new-api 时代的存量档位 —— 它们已经是「卖不出去、也发不出积分」的死行。
--
-- ── 这批行现在是什么状态（为什么要清）──────────────────────────────────────────
-- 迁移 048 把基础积分从「派生」（原价 × 换算率）改成**配置值**，存量行一律落 0 = 还没配过。
-- 而 048 之后的下单路径**只认 `base_credits`**：0 积分的档位会被 `RechargeService.createOrder`
-- 拒绝（fail-closed —— 宁可下不了单，也不发 0 积分）。于是这批行在用户端是一张「0 积分」的
-- 卡片，点下去必然被拒：不是「暂时不能用」，是**每一档都点不动**。
-- 它们不是商品，是挂着商品外形的残留数据。运营若要卖那个价位的东西，正确做法是新建一档
-- 或改一档并填上基础积分 —— 而不是把一行 0 积分的旧档留在目录里。
--
-- ── 界定条件为什么是 `base_credits = 0`，而不是「名字不在 PRD 那 6 档里」────────────
--   1. **它就是「不可售」的定义本身**：读路径唯一认的积分来源是 `base_credits`，
--      0 = 这行下不了单。删掉「恰好等于卖不出去的那批行」，不留解释空间。
--   2. **名字是运营可改的配置，不是主键**。迁移 049 自己写着「代码里没有任何地方再引用
--      这 6 个名字……运营删掉某一档、改名、改价，都不会被本文件纠正回来」。
--      按名字界定等于当场推翻那句话：运营把「重度创作」改成「团队年度」之后，一次按名字
--      的清理会把它**连同它已配好的 90,000 积分一起软删** —— 一个能卖的商品被数据迁移下架。
--   3. **不依赖 049 是否跑过**。按名字的条件在一个还没 seed 的环境里没有可命中的行，语义会
--      退化成「删掉表里所有档位」；而 `base_credits = 0` 在那个环境里删掉的正是同一批死行
--      （它们本来就一行都卖不出去），且如果那个环境里有人**手工配过**某一档的基础积分，
--      那一行会被留下 —— 这是两者唯一的差别，也是我们要的那一边。
--   一句话：留下来的判据是「这行还能不能卖」，不是「它是不是我们种下的那 6 行」。
--
-- ⚠️ 本迁移**不依赖 `id`**：21–26 只是本地库的自增值，别的环境不是这个数。
--
-- ── 软删，不是物理删 ───────────────────────────────────────────────────────────
-- 本表的既有约定就是 `is_delete`（`TopupTierRepo` 的每条读路径都带 `is_delete = 0`）。
-- 更要紧的是：这些行的 `id` 被**历史订单**的 `recharge_orders.tier_id` 引用着
-- （订单行里另有下单时刻的名称快照 `product_name`，但那不能替代按 id 反查档位）。
-- 物理删 = 老订单指向一个查不到的档位；软删 = 用户端/管理端列表里消失（读路径都过滤
-- is_delete），而历史订单仍能反查到它当初是哪一档。**这正是这张表当初设 is_delete 的原因。**
--
-- ── 只动 `is_delete = 0` 的行 ─────────────────────────────────────────────────
-- 已经软删过的行不再更新：把它们的 `gmt_modified` 刷成今天，等于抹掉「它是什么时候被下架的」
-- 这个唯一痕迹（本表没有单独的删除时刻列）。
--
-- ── 前置校验（执行前人工确认，须有输出）──────────────────────────────────────
--   SELECT COUNT(*) AS will_soft_delete FROM topup_tiers WHERE is_delete = 0 AND base_credits = 0;
--   SELECT id, name, base_credits, status, is_delete FROM topup_tiers ORDER BY id;
-- 第一条给出**即将软删的行数**，第二条是删之前的全量快照（人工扫一眼有没有本该保留的行）。
-- ⚠️ 在一个只卖 PRD 那 6 档的环境里，这两个数应当互补：
--    `will_soft_delete` = **在架行数**（`is_delete = 0`）− 6（049 种下的那 6 档）。
--    已经软删的行**不算在内**（它们本来就不在这次清理范围内，只是留在这张表里的历史行）。
--    对不上就先停手 —— 说明有人配过（或删过）档位，先问清楚再执行。
--
-- ── 回读验证（执行后）────────────────────────────────────────────────────────
--   SELECT id, name, base_credits, status, is_delete FROM topup_tiers ORDER BY id;
-- `is_delete = 0` 剩下的应当正是 `base_credits > 0` 的那几行（本环境即 PRD §6.1 的 6 档）。
SET NAMES utf8mb4;

UPDATE `topup_tiers`
SET `is_delete` = 1,
    `gmt_modified` = NOW()
WHERE `is_delete` = 0
  AND `base_credits` = 0;
