-- 退役 `user_info` 表：网关侧执行凭证（sk-）镜像的最后一截。
--
-- ── 这张表是什么 ──────────────────────────────────────────────────────────────
-- ADR-0087 引入：登录成功时把用户的执行凭证（sk-）按 user_id **明文**抄一份，供 worker-java
-- 的素材状态定时兜底「以素材归属用户身份」代打网关（网关无服务级查询入口）。
--
-- ── 为什么现在删 ──────────────────────────────────────────────────────────────
-- ADR-0115 决策 1 把身份自建、new-api 降级为「上游供应商」（一个客户号、一把 key，没有用户
-- 概念），ADR-0117 决策 4 据此把本表列为**整表删除**。落地之后它连一个读者都不剩：
--   * **写入端已删**，回归闸钉在 `backend/apps/blue-whale/src/api/auth/auth.controller.test.ts`
--     （「★ 再没人写 user_info 凭证行」）。
--   * **读取端零调用** —— `createUserInfoRepo` 全仓无调用者（只在自己文件与 persistence 桶导出
--     里出现）。本迁移同时删掉该 repo 文件与 `schema.prisma` 的 model，两边一起走。
--   * **worker-java 从来不读它** —— 素材状态定时跟进改读 `system_settings` 的 upstream 行
--     （`MaterialStatusPoller` → `UpstreamCredential.requireKey()`，见 ADR-0114 决策 7）。
-- 全项目共用一把 key 之后，这张表存的只是**同一份密文按 userId 抄的 N 份副本**，无信息量。
--
-- ── `IF EXISTS` 是刻意的 ──────────────────────────────────────────────────────
-- 本表的创建在 `20260915170000_ikfyhj_material_compliance`（编号序列 025）。任何没跑过那一条
-- 的环境（比如只按 baseline 起过的本地库）里它本就不存在，不带 `IF EXISTS` 会让迁移中断。
--
-- ── 不可逆 ────────────────────────────────────────────────────────────────────
-- 与 20260924180000 / 20260928100000 那类「改名失败可补跑」的迁移不同：DROP 之后只能重建。
-- 表内没有独立价值的数据（见上），若要留档，执行前自行取一份即可：
--   SELECT * FROM `user_info`;
--
-- ── 回读验证（执行后）────────────────────────────────────────────────────────
--   SHOW TABLES LIKE 'user_info';         -- 应为空
--   SHOW TABLES LIKE 'material_assets';   -- 应有值（同一条迁移建的表，不该被误伤）
SET NAMES utf8mb4;

DROP TABLE IF EXISTS `user_info`;
