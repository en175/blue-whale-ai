-- 预扣时冻结的**规则本身**（《计费逻辑详细设计》§2.4 / §4.3）
--
-- ── 为什么还要再冻一份「规则」──────────────────────────────────────────────────
-- 这条规则原先住在定价目录（billing_pricing_catalogs.document 的
-- models.<model_id>.<task_type>）。现在它搬进了**模型能力行**
-- （backend 的 generation_model_capability.pricing）——理由是它本质上是模型的属性
-- （单价 / 计价方式 / 单位分母 / 上下限 / token 公式参数）。
--
-- 而 billing 读不到那个库（ADR-0114：不共享库），所以由属主在 Hold 时把这份规则
-- 随请求送过来。于是结算面临一个新问题：**回读目录已经读不到这条规则了**。
-- 所以要把**规则本身**冻下来，让结算不必回读目录。
--
-- ── 与 catalog_version / discount_bp 的关系 ────────────────────────────────────
-- 三者是同一次冻结的三条腿：
--   catalog_version  当时生效的是哪一版目录（**仅作追溯**，结算不再按它回读）
--   discount_bp      当时打了多少折（结算复现折扣用它）
--   rule_snapshot    ★ 当时那条规则长什么样（结算复现规则用它）
--
-- ── ⚠️ NULL 的含义：算不出价 ───────────────────────────────────────────────────
-- NULL = 这次预扣没有带快照。**没有回落这回事**——目录里已经不放模型规则了
-- （它现在只装 creditsPerYuan 与 discountPolicy 两项全局配置），
-- 所以这类预留结算时直接抛出去让 MQ 重投，而不是去目录里找一条不存在的规则。
--
-- 说明：本迁移最初写的是「NULL = 回落按 catalog_version 读目录」。那条回落路径
-- （以及目录里的 models 段）在同一批工作里被删掉了，因为**这套 billing 从未部署过**
-- ——目录里那 13 条规则对应的能力行全部已有 pricing，仅有的十几条「没快照」的预留
-- 是本地测试数据。留一个没有保护对象的兼容分支就是留屎山。
--
-- ── 为什么是 TEXT 而不是 JSON 列 ───────────────────────────────────────────────
-- 这一列是**送来的那串字节**：billing 只把它原样再喂给 CatalogCompiler。
-- MySQL 的 JSON 列会规范化文本（键按长度重排、冒号后补空格），存进去与读出来不是同一串；
-- 而它的校验与索引能力在这里**没有用处**——写入前已经编译过（编不过直接拒单，不进库），
-- 也从不按内容做任何 SQL 查询。所以用 TEXT：所见即所存。
--
-- ADR-0113 的数据主权：本列的内容由 backend 送来，billing 只负责存与再编译。
ALTER TABLE billing_cost_reservations
  ADD COLUMN rule_snapshot TEXT NULL
    COMMENT '冻结的计价规则快照（JSON 文本，形态与能力行 generation_model_capability.pricing 逐字相同）；NULL = 本次预扣没带快照 → 结算算不出价、拒绝并重投'
    AFTER discount_bp;
