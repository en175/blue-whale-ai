-- 结算时「用量已发生、但没收到的钱」——欠费额（《计费逻辑详细设计》§2.4 / §4.4）
--
-- ── 为什么要在预留行上把「欠费」单列出来 ─────────────────────────────────────
-- 一次结算里其实有**三个**不同的金额，此前它们全挤在一个数里，谁也说不清：
--
--   actual_credits     这次真实用掉多少（成本口径，**上游说了算**）
--   receivable_credits 其中有多少**没能从用户余额里收到**（本列新增）
--   实收               = actual_credits − receivable_credits（= 用户实际被扣走的）
--
-- 只记 actual_credits 时，管理端「总使用积分」按它求和，而用户实际被扣的是
-- min(actual, reserved)——两个数天生不等，且差额**只以一条应收账款分录的形式**
-- 躺在账本里。于是「用户欠了多少钱」这个问题，全仓没有任何一处读得出来：
-- 没有列、没有接口、没有页面，只有翻账本。
--
-- ⚠️ 这一列**不是**为了换个地方算钱。它记的正是账本上那一腿
-- （settle 里 `voucher.debit(Account.RECEIVABLE, …)`，见 CreditService）的同一个数，
-- 两者由**同一次结算、同一个表达式**写下，所以可以逐笔对账：
-- 某段时间内 Σ receivable_credits 必须等于这段时间账本 RECEIVABLE 的增量。
-- 这正是「按 job 记账」与「按用户汇总」之间唯一能对上的那个连接点。
--
-- ── 产品口径：先欠费 ──────────────────────────────────────────────────────────
-- 产品已确认走「先欠费」：**只记录、只可见，不收款、不封禁、不拦截**。
-- 所以这一列是**信号**，不是催收凭证——它的全部价值是让运营看得见
-- 「哪些用户在用超、超了多少」，而不是驱动任何自动动作。
--
-- ── 为什么 DEFAULT 0 对存量行是对的 ──────────────────────────────────────────
-- 存量行结算时还没有这一列，而它们绝大多数本来就没有超扣（差额恒为 0）；
-- 真正超扣过的那几条，其账本 RECEIVABLE 分录仍在，可人工核对补齐——
-- 反过来给存量行猜一个非零值才是编造数据。
--
-- 说明：`actual_credits` 的语义**不变**——它一直是「真实用量成本」，那是对的。
-- 本次只是补上「其中有多少没收到」，不是把它的口径改成实收。
ALTER TABLE billing_cost_reservations
  ADD COLUMN receivable_credits BIGINT NOT NULL DEFAULT 0
    COMMENT '欠费额（整数积分）：本次结算中「实际 > 预扣」的差额，与账本 RECEIVABLE 那一腿同数。实收 = actual_credits − receivable_credits。0 = 没有超扣（含全部存量行）'
    AFTER actual_credits;
