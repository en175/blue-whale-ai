/* ============================================
 * 表单栅格 —— **全管理端唯一一套列宽与间距**
 *
 * ── 为什么要有它 ──────────────────────────────────────────────────────────────
 * 在这之前，9 个管理页各自手写 `gridTemplateColumns`，间距出现 5 种取值
 * （`16px 24px` / `24px 40px` / `20px 24px` / `16px 20px` / `12px`）。
 * 于是同一个管理端里：输入框一会半宽一会整宽、字段一会高一会低、上下两页的留白对不上。
 * 「每页各自写一套」不是灵活，是**没有栅格**。
 *
 * 栅格是**版式**，不是页面的事 —— 所以它住套件里，与按钮、输入框同级。
 *
 * ── 三条硬约束 ────────────────────────────────────────────────────────────────
 * 1. `minmax(0, 1fr)` 而不是 `1fr`：栅格子项默认 `min-width: auto`，内容偏宽时
 *    （Select 的选项文案、长 URL）会把列撑破，整行跟着错位。加 `minmax(0, …)` 才真等宽。
 * 2. **间距写在这里，不写在使用处**：页面再传 `gap` 就等于又回到各写各的。
 * 3. `alignItems: start`：同一行里一个字段带说明、一个不带时，两个控件仍顶部对齐 ——
 *    默认的 `stretch` 会把矮的那个拉高，看起来「一会上、一会下」。
 *
 * <p>用法：`<div style={formGrid(2)}>…</div>`，要加一次性外边距就
 * `style={{ ...formGrid(3), marginTop: 12 }}`（只允许覆盖外边距）。
 * ============================================ */
import type { CSSProperties } from 'react';

/** 字段栅格：列数默认 2。列宽与间距由本函数唯一决定。 */
export function formGrid(columns: 1 | 2 | 3 = 2): CSSProperties {
  return {
    display: 'grid',
    gridTemplateColumns: `repeat(${columns}, minmax(0, 1fr))`,
    // 间距**只取尺度上的值**（4/8/12/16/24）：行 16、列 24 —— 列比行宽是为了让「两列」读得出
    // 是两列。与 Field 自身的 gap(6) 叠成「字段内 6、字段间 16」的两级节奏。
    gap: 'var(--admin-space-4) var(--admin-space-5)',
    marginBottom: 'var(--admin-space-5)',
    alignItems: 'start',
  };
}
