/**
 * 说明性文字 —— 一个「?」图标，悬停 / 聚焦才显示内容。
 *
 * <h2>全管理端只有这一种「解释」的形态</h2>
 *
 * 在此之前，解释一律铺成整块蓝色 `Alert tone="info"`：一屏下来**解释比控件还占地方**，
 * 要填的东西被顶到折叠线以下，而真正需要看说明的时刻（不知道某个键该怎么填）只是偶尔。
 * 说明该在**需要时**出现。
 *
 * <p>判据只有一条：**它解释的是「这是什么 / 为什么」，还是「现在是什么」。**
 *   · 「这是什么 / 为什么」→ 本组件（`?` 图标，悬停看）；
 *   · 「现在是什么」（当前值、生效版本、已启用条数、加载中、错误）→ 保持可见的 Alert——
 *     藏起来就等于把状态藏起来，那是另一种看不见。
 *
 * <p>⛔ 不要再用 `Alert tone="info"` 写解释：那是这套口径之前的形态，留着会让同一个管理端
 * 出现两种「说明」，而这正是要消灭的不统一。
 *
 * <p>⚠️ 图标是**行内元素**：写在标题 / 标签行里才贴着它说明的东西；单独一行也只占一个
 * 图标的宽度，不再撑出一整块色块。
 *
 * <h2>写内容的两条要求</h2>
 *
 * 1. **别写字面量 markdown**：这里是 JSX，`**加粗**` 会原样渲染成星号。要强调就用 `<b>`。
 * 2. **一句话一件事，该断就断**：面板宽 380px、高封顶 420px，四行连排会变成一坨。
 *    分段用 `<div>` 包一层（段落间距见 `Tooltip/index.module.css`）。
 */
import type { ReactNode } from 'react';
import Tooltip from '../Tooltip';

export default function Hint({
  children,
  title,
  label = '说明',
}: {
  children: ReactNode;
  /** 面板标题。长说明给它一个标题，读者才知道这段在回答什么。 */
  title?: ReactNode;
  label?: string;
}) {
  return <Tooltip title={title} content={children} label={label} />;
}
