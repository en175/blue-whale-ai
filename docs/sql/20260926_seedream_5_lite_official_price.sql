-- Seedream 5.0 Lite 输出单价对齐官方：0.12 元/张 → **0.22 元/张**。
--
-- ── 依据（火山方舟官方，多来源一致）────────────────────────────────────────────
--   Doubao-Seedream-5.0-lite（本行 model_id `doubao-seedream-5-0-260128`）：
--   **0.22 元/张**，按张计费 —— 与 prompt 长度、是否多图融合、输出尺寸**都无关**；
--   失败请求（4xx / 内容审核拦截）不计费。
--   同门对照（本仓已有值）：Seedream 4.5 = 0.25 元/张、4.0 = 0.20 元/张。
--
--   参考图：**本模型输入参考图完全免费**（不是「首张免费」——那条是 5.0 **Pro** 的规则：
--   Pro 输出图 ≤236 万像素 0.3 元 / >236 万 0.6 元、输入图首张免费第 2 张起 0.02 元/张）。
--   所以本迁移**不动参考图**：Lite 本来就不该收。
--
-- ── 原值错在哪 ───────────────────────────────────────────────────────────────
-- 原值 1800 mc = 1.8 积分 = **0.12 元/张**，比官方低 45%。
-- 这行的 `basePrice` 还挂在 `by:["size"]` 上，但三个档（2k/3k/4k）填的是**同一个数**
-- —— 那根尺寸轴在这条规则里没有任何读方，是「配了却没人读」的形态（官方按张计费，
-- 与尺寸无关）。本次一并收成常数，与同族的 4.5 同形。
--
-- ── 关于 1 积分的粒度（不是配错，但要知情）────────────────────────────────────
--   0.22 元 × 15 积分/元 = **3.3 积分**，而积分是整数。
--   默认舍入 halfUp：3.3 → **3 积分 = 0.2 元**（比官方少 0.02 元/张）。
--   若改 ceil：4 积分 = 0.267 元（比官方多 0.047 元/张）——偏离更大，故不改。
--   同门 4.5 是 0.25 元 = 3.75 积分 → halfUp → 4（多 0.017 元），同一层粒度误差。
--   要消掉它得让积分支持小数，那是货币粒度的事，不在本次范围。
--
-- ── 前置校验（执行前人工确认，须有输出）──────────────────────────────────────
--   SELECT model_id, model_label, pricing FROM generation_model_capability
--    WHERE model_id = 'doubao-seedream-5-0-260128';
SET NAMES utf8mb4;

UPDATE `generation_model_capability`
SET `pricing` = JSON_OBJECT(
      'baseUnit', 'usage.succeededSlots',
      'basePrice', JSON_OBJECT('kind', 'const', 'value', 3300),
      'unitDenominator', 1,
      'minCredits', 1
    )
WHERE `model_id` = 'doubao-seedream-5-0-260128'
  AND `capability_type` = 'image'
  AND `is_delete` = 0;
