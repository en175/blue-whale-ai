-- generation_jobs 补 (is_delete, gmt_create) 索引（仪表盘区间统计）。
--
-- ── 为什么需要它 ──────────────────────────────────────────────────────────────
-- 管理端仪表盘按「时间段」统计任务数与类型占比：
--
--   WHERE is_delete = 0 AND gmt_create >= ? AND gmt_create < ?
--
-- 而 `gmt_create` **此前没有任何索引** —— 每打开一次仪表盘就是对整张生成任务表
-- 一次全表扫描。30 天上限限制的是**结果行数**，不是**扫描量**，
-- 所以任务越积越多，这个页面就越来越慢，而它恰恰是运营每天第一个打开的页面。
--
-- ── 为什么是这两列、这个顺序 ──────────────────────────────────────────────────
-- `is_delete` 放在前面做等值前缀，`gmt_create` 跟在其后走区间扫描 ——
-- 这样索引能被"前导列等值 + 次列范围"利用到。反过来放的话，
-- 范围列在前会让等值条件退化成过滤，索引基本白建。
--
-- ── 为什么不是仅 (gmt_create) ─────────────────────────────────────────────────
-- 单列也能用，但 `is_delete = 0` 就得回表逐行判断。软删是常态字段，
-- 带上它不额外增加索引宽度，却省掉一次回表过滤。
--
-- ⚠️ 大表加索引会锁写。本表当前量级（万级）下是秒级操作；
--    若线上已到百万级，需要走在线 DDL（pt-online-schema-change / gh-ost）。
SET NAMES utf8mb4;

ALTER TABLE `generation_jobs`
    ADD INDEX `idx_generation_jobs__is_delete_gmt_create` (`is_delete`, `gmt_create`);
