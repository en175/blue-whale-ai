-- 通用积分卡：订单存收银台链接（复用未支付单）+ 记「首次进入待到账」的时刻（主动对账）。
--
-- 依据 PRD §7.5「服务端避免重复有效订单」/ §9.1（订单状态机）与 #45（主动对账）。
--
-- ── `cashier_url`：为什么链接必须落库 ──────────────────────────────────────────
-- 用户再点一次「立即支付」时，我们要把**同一笔单的同一条链接**还给他，而不是新建一笔
-- （每点一次建一笔 = 每点一次打一次网关；两条链接都有效，用户还可能两条都扫、付两笔）。
--
-- 而链接**不能事后重新要一个**：网关的支付订单按 (`mch_no`, `mch_order_no`) 唯一
-- （`Uni_MchNo_MchOrderNo`），拿同一个商户订单号再下一次单会被拒成「商户订单[..]已存在」。
-- 所以只能在下单应答那一刻把它存下来；银行收银台令牌 30 分钟后失效，链接也就随之作废。
--
-- 可空：本列上线前的订单没有它（那批单的链接拿不出来，不可复用），下单时网关调用失败的单
-- 也不会有。⚠️ 判「这单究竟拿到过链接没有」**不看这一列**，看 `pay_order_id` ——
-- 两者由同一次更新写入，同真同假，而「网关订单号为空」才是「网关那一步就没成功」的判据。
--
-- ── `paid_pending_at`：主动对账的时钟起点 ──────────────────────────────────────
-- 「支付成功后超过 30 分钟还没发完积分 = 到账异常」这条规则需要一个「钱到账的时刻」：
--   · `gmt_modified` 顶替不了 —— 回调到达（`recordNotify`）、查单名额（`claimQuerySlot`）都会改它；
--   · `paid_at` 也不行 —— 那是「积分发出去」的时刻，而这里要的恰恰是它之前的那个时刻。
-- 写入点全仓只有一处（`markPaidPending` 的条件更新），所以它天然是「**首次**进入待到账」的时刻：
-- 回调重投、异常单回炉都不会把它刷新成「刚才」——否则「持有分钟数」永远停在几分钟，看起来一切正常。
--
-- 可空：本列上线前进入 `paid_pending` 的存量单没有它，取数侧对那种行退回按下单时刻判
-- （更宽松，好过永远扫不到）。
--
-- ── 为什么不给主动对账加索引 ──────────────────────────────────────────────────
-- 它的取数是 `status IN ('paid_pending','grant_failed') AND 时刻 < cutoff`，5 分钟一轮。
-- 037 已经把口径定过一遍：`status` 是低基数列，单独建索引选择性差；要覆盖这里还得再加
-- `(is_delete, status, paid_pending_at)` —— 为一个每 5 分钟一次、结果通常是空集的扫描，
-- 让每一次订单写入都多维护一棵索引树，不值。当前量级（万级以下）走
-- `idx_recharge_orders__is_delete_gmt_create` 顺序扫描 + 过滤即可。
-- 若线上单量到百万级、或 `grant_failed` 长期堆积到影响这一扫，再回来加它。
SET NAMES utf8mb4;

ALTER TABLE `recharge_orders`
  ADD COLUMN `cashier_url` VARCHAR(512) NULL
    COMMENT '银行统一收银台链接（下单应答的 payData，内嵌银行令牌）。落库是为了复用未支付订单——网关不允许同一 mchOrderNo 重下一次单，这条链接事后要不回来',
  ADD COLUMN `paid_pending_at` DATETIME(0) NULL
    COMMENT '首次进入 paid_pending（钱到了、积分还没发）的时刻。主动对账据此算持有分钟数；gmt_modified 会被回调与查单改写，不能顶替';
